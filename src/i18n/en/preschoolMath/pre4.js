const P34 = [46, 39, 68, 38, 65, 40, 41, 47, 66, 89, 36, 63, 52, 45, 72, 44, 33, 64, 61, 49, 92, 34, 69, 67, 48, 36];
const COLOR_RULES = [[50, 60, 'màu vàng', 'yellow'], [60, 70, 'màu nâu', 'brown'], [70, 80, 'màu hồng', 'pink'], [80, 90, 'màu xanh lá', 'green'], [90, 100, 'màu xám', 'gray']]
  .map(([lo, hi, vi, color]) => [lo, hi, vi, color, P34.filter(v => v > lo && v < hi)]);
const colorEntries = Object.fromEntries(COLOR_RULES.flatMap(([lo, hi, vi, color, found]) => {
  const k = found.length;
  return [
    [`Số lớn hơn ${w(lo)}, nhỏ hơn ${w(hi)} thì tô ${vi}. Bé tìm và chạm vào ${k > 1 ? `tất cả ${w(k)} số` : 'số'} đó!`,
      `Numbers greater than ${en(lo)} and less than ${en(hi)} are colored ${color}. Find and tap ${k > 1 ? `all ${en(k)} of them` : 'that number'}!`],
    [`Chưa đúng rồi. Bé tìm số lớn hơn ${w(lo)} và nhỏ hơn ${w(hi)}!`, `Not quite. Find a number greater than ${en(lo)} and less than ${en(hi)}!`],
    k > 1 ? [`Giỏi quá! Bé tìm đủ các số để tô ${vi} rồi!`, `Great job! You found all the numbers to color ${color}!`]
      : [`Đúng rồi! Số ${w(found[0])} tô ${vi}!`, `Correct! The number ${en(found[0])} is colored ${color}!`],
  ];
}));
